import { test } from "node:test";
import assert from "node:assert/strict";
import * as mod from "./change-size.mjs";
import { makeRepo } from "../test/helpers/repo.mjs";

const cfg = { tests: { files: ["test/", "**/*.test.mjs"] }, brakes: { changeSize: { warn: 10, max: 20 } } };
const lines = (n, p = "x") => Array.from({ length: n }, (_, i) => `${p}${i}\n`).join("");
const withRepo = (fn, config = cfg) => async () => {
  const repo = makeRepo({ config, files: { "src/a.js": "a\n" } });
  try { repo.branch("feat"); await fn(repo); } finally { repo.cleanup(); }
};

test("needs tests.files", () => assert.deepEqual(mod.needs, ["tests.files"]));

test("small change passes with no lines", withRepo(async (repo) => {
  repo.commit("small", { files: { "src/b.js": lines(3) } });
  assert.deepEqual(await repo.run(mod), { ok: true, lines: [] });
}));

test("over warn passes with a note", withRepo(async (repo) => {
  repo.commit("mid", { files: { "src/b.js": lines(12) } });
  const r = await repo.run(mod);
  assert.equal(r.ok, true);
  assert.equal(r.lines.length, 1);
}));

test("over max fails: count, limit, three largest files", withRepo(async (repo) => {
  repo.commit("big", { files: { "src/b.js": lines(9), "src/c.js": lines(8), "src/d.js": lines(7), "src/e.js": lines(1) } });
  const r = await repo.run(mod);
  assert.equal(r.ok, false);
  assert.match(r.lines[0], /25/);
  assert.match(r.lines[0], /20/);
  const rest = r.lines.slice(1).join("\n");
  for (const f of ["src/b.js", "src/c.js", "src/d.js"]) assert.ok(rest.includes(f));
  assert.ok(!rest.includes("src/e.js"));
}));

test("tests, docs, fixtures, json, lockfile, .graphifyignore are not counted; sql is", withRepo(async (repo) => {
  repo.commit("noise", { files: {
    "test/t.js": lines(30), "docs/x.txt": lines(30), "README.md": lines(30), "src/fixtures/f.js": lines(30),
    "src/d.json": lines(30), "package-lock.json": lines(30), "yarn.lock": lines(30),
    "vendor/v.js": lines(30), "gen/g.js": lines(30), "src/m.min.js": lines(30),
    ".graphifyignore": "# generated\nvendor/\ngen\n*.min.js\n" } });
  assert.deepEqual(await repo.run(mod), { ok: true, lines: [] });
  repo.commit("sql", { files: { "db/m.sql": lines(25) } });
  assert.equal((await repo.run(mod)).ok, false);
}));

test("removed lines count too", async () => {
  const repo = makeRepo({ config: cfg, files: { "src/old.js": lines(12, "o") } });
  try {
    repo.branch("feat");
    repo.commit("rewrite", { files: { "src/old.js": lines(12, "n") } }); // 12 added + 12 removed
    assert.equal((await repo.run(mod)).ok, false);
  } finally { repo.cleanup(); }
});

test("size-ok passes and prints its reason", withRepo(async (repo) => {
  repo.commit("big", { files: { "src/b.js": lines(40) }, body: "size-ok: generated by hand-run script" });
  const r = await repo.run(mod);
  assert.equal(r.ok, true);
  assert.match(r.lines.join("\n"), /generated by hand-run script/);
}));

test("main push: the largest merged batch is judged, and named", withRepo(async (repo) => {
  repo.checkout("main");
  repo.branch("small"); repo.commit("small one", { files: { "src/s.js": lines(5) } });
  repo.checkout("main"); repo.merge("small", "merge small");
  repo.branch("large"); repo.commit("large one", { files: { "src/l.js": lines(30) } });
  repo.checkout("main"); repo.merge("large", "merge large");
  const r = await repo.run(mod, { ref: "refs/heads/main" });
  assert.equal(r.ok, false);
  assert.match(r.lines.join("\n"), /merge large/);
  assert.ok(!r.lines.join("\n").includes("merge small"));
}));

test("main push: two batches each under max pass though the sum is over", withRepo(async (repo) => {
  repo.checkout("main");
  for (const n of ["one", "two"]) {
    repo.branch(n); repo.commit(`${n} work`, { files: { [`src/${n}.js`]: lines(15) } });
    repo.checkout("main"); repo.merge(n, `merge ${n}`);
  }
  assert.equal((await repo.run(mod, { ref: "refs/heads/main" })).ok, true);
}));

test("a file marked -diff by attributes still counts its lines", withRepo(async (repo) => {
  repo.write(".git/info/attributes", "* -diff\n");
  repo.commit("big", { files: { "src/b ï.js": lines(30) } });
  const r = await repo.run(mod);
  assert.equal(r.ok, false);
  assert.match(r.lines[0], /30/);
}));

test("a file that really holds a NUL byte counts 0", withRepo(async (repo) => {
  repo.commit("bin", { files: { "src/b.bin": `${lines(30)}\0\n` } });
  assert.deepEqual(await repo.run(mod), { ok: true, lines: [] });
}));

test("non-numeric warn or max cannot run", async () => {
  const bad = { ...cfg, brakes: { changeSize: { warn: 10, max: "eight hundred" } } };
  await withRepo(async (repo) => {
    repo.commit("big", { files: { "src/b.js": lines(30) } });
    const r = await repo.run(mod);
    assert.equal(r.ok, false);
    assert.equal(r.cannotRun, true);
  }, bad)();
});
